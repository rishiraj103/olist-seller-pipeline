-- Every dimension has a -1 "Unknown" row so facts never need a NULL foreign key.

-- Role-playing date dimension: purchase, approved, shipped, delivered, estimated.
CREATE TABLE IF NOT EXISTS dw.dim_date (
    date_key     integer PRIMARY KEY,            -- YYYYMMDD, -1 = unknown / not reached
    full_date    date        NOT NULL UNIQUE,
    year         smallint    NOT NULL,
    quarter      smallint    NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    month        smallint    NOT NULL CHECK (month BETWEEN 1 AND 12),
    month_name   text        NOT NULL,
    day          smallint    NOT NULL CHECK (day BETWEEN 1 AND 31),
    day_of_week  smallint    NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),  -- ISO: 1 = Monday
    is_weekend   boolean     NOT NULL
);

-- SCD Type 1: one row per real customer, latest address overwrites.
CREATE TABLE IF NOT EXISTS dw.dim_customer (
    customer_key        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_unique_id  text    NOT NULL UNIQUE,
    zip_code_prefix     char(5) NOT NULL,
    city                text    NOT NULL,
    state               char(2) NOT NULL,
    updated_batch_id    text    NOT NULL
);

-- SCD Type 2: one row per seller version; history kept when city/state change.
CREATE TABLE IF NOT EXISTS dw.dim_seller (
    seller_key       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id        text    NOT NULL,
    zip_code_prefix  char(5) NOT NULL,
    city             text    NOT NULL,
    state            char(2) NOT NULL,
    row_hash         text    NOT NULL,           -- md5(city|state): tracked columns
    effective_start  date    NOT NULL,
    effective_end    date    NOT NULL DEFAULT DATE '9999-12-31',
    is_current       boolean NOT NULL DEFAULT true,
    CHECK (effective_end >= effective_start),
    UNIQUE (seller_id, effective_start)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_dim_seller_current ON dw.dim_seller (seller_id) WHERE is_current;

-- SCD Type 1: one row per product, corrections overwrite.
CREATE TABLE IF NOT EXISTS dw.dim_product (
    product_key                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id                  text NOT NULL UNIQUE,
    category_name               text NOT NULL,   -- Portuguese, 'unknown' if missing
    category_name_english       text NOT NULL,
    product_name_length         smallint,
    product_description_length  integer,
    product_photos_qty          smallint,
    product_weight_g            integer CHECK (product_weight_g >= 0),
    product_length_cm           smallint,
    product_height_cm           smallint,
    product_width_cm            smallint,
    updated_batch_id            text NOT NULL
);

